"""Creates a new seed braider for every fully verified seed Stripe test account
that no braider in this database uses yet, and links them - so Stripe test
accounts left over from earlier runs (whose braiders were pruned, or were
created by an interrupted run) become usable braiders instead of waste.

Test-mode Stripe caps account *creation* (~450-500 in a burst); this only
reads and updates existing accounts, which isn't capped.

Each new braider takes the account's country, city, first/last name and
business name, so the app and the Stripe dashboard agree. The Stripe
account's `metadata.braider_id` and `email` are then updated to point at the
new braider. Logos/portfolios start on the placeholder images - run
scripts.seed_braider_images afterwards to give them real photos.

Refuses to run unless STRIPE_SECRET_KEY is a test key.

Run from the repo root:
    python -m scripts.adopt_orphan_stripe_accounts --dry-run
    python -m scripts.adopt_orphan_stripe_accounts
    python -m scripts.seed_braider_images
"""
import argparse
import asyncio
from typing import Any

import stripe
from sqlalchemy import select

from app.core.config import get_settings
from app.core.database import AsyncSessionLocal
from app.core.security import hash_password
from app.modules.braiders.models import BraiderProfile
from app.modules.braiders.payment_setup.models import StripeConnectAccount
from app.modules.styles.models import Style
from app.modules.users.models import User
from scripts.link_seed_braiders_stripe import _apply
from scripts.seed_braiders import (
    _CITIES_BY_COUNTRY,
    _STYLE_SLUGS,
    SEED_PASSWORD,
    BraiderIdentity,
    build_braider,
    is_seed_user,
)


def _free_seed_accounts_sync(used_ids: set[str]) -> list[Any]:
    accounts = []
    for account in stripe.Account.list(limit=100).auto_paging_iter():
        if (account.metadata or {}).get("seed") != "true" or account.id in used_ids:
            continue
        if not (account.charges_enabled and account.payouts_enabled):
            continue
        if account.country not in _CITIES_BY_COUNTRY:
            continue
        accounts.append(account)
    return sorted(accounts, key=lambda a: a.created)


def _identity(account: Any) -> BraiderIdentity:
    individual = account.individual
    business = account.business_profile
    first_name = (individual.first_name if individual else None) or "Amara"
    return {
        "country": account.country,
        "city": (individual.address.city if individual and individual.address else None) or "",
        "first_name": first_name,
        "last_name": (individual.last_name if individual else None) or "Braider",
        "business_name": (business.name if business else None) or f"{first_name}'s Braids",
    }


def _update_account_sync(account_id: str, braider_id: str, email: str) -> None:
    stripe.Account.modify(account_id, email=email, metadata={"braider_id": braider_id})


async def main(dry_run: bool) -> None:
    if not get_settings().stripe_secret_key.startswith(("sk_test_", "rk_test_")):
        raise SystemExit("Refusing to run: STRIPE_SECRET_KEY is not a Stripe *test* key.")

    async with AsyncSessionLocal() as db:
        used_ids = set((await db.execute(select(StripeConnectAccount.stripe_account_id))).scalars())
        accounts = await asyncio.to_thread(_free_seed_accounts_sync, used_ids)
        print(f"{len(accounts)} unused, fully enabled seed Stripe account(s) found.")
        if dry_run or not accounts:
            return

        # New braiders get indices after the highest existing seed email, so
        # they never collide with (or get re-generated by) seed_braiders.
        emails = (await db.execute(select(User.email).where(is_seed_user()))).scalars()
        next_index = max((int(e[len("braider") : len("braider") + 5]) for e in emails), default=0) + 1

        style_ids = {
            slug: style_id
            for slug, style_id in await db.execute(
                select(Style.slug, Style.id).where(Style.slug.in_(_STYLE_SLUGS))
            )
        }
        password_hash = hash_password(SEED_PASSWORD)

        users: list[object] = []
        user_children: list[object] = []
        profile_children: list[object] = []
        links: list[tuple[str, str, str]] = []  # (stripe account id, braider id, email)
        for offset, account in enumerate(accounts):
            user, uc, pc = build_braider(
                next_index + offset, password_hash, style_ids, _identity(account)
            )
            profile = next(row for row in uc if isinstance(row, BraiderProfile))
            connect_row = next(row for row in pc if isinstance(row, StripeConnectAccount))
            _apply(connect_row, account)
            users.append(user)
            user_children.extend(uc)
            profile_children.extend(pc)
            links.append((account.id, str(profile.id), user.email))

        db.add_all(users)
        await db.flush()
        db.add_all(user_children)
        await db.flush()
        db.add_all(profile_children)
        await db.commit()
        print(f"Created and linked {len(users)} braider(s).")

    semaphore = asyncio.Semaphore(8)

    async def update(link: tuple[str, str, str]) -> bool:
        async with semaphore:
            try:
                await asyncio.to_thread(_update_account_sync, *link)
                return True
            except stripe.error.StripeError as exc:
                print(f"  ! {link[0]}: {exc}")
                return False

    updated = sum(await asyncio.gather(*(update(link) for link in links)))
    print(f"Pointed {updated}/{len(links)} Stripe account(s) at their new braider.")
    print("Next: python -m scripts.seed_braider_images")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--dry-run", action="store_true")
    asyncio.run(main(parser.parse_args().dry_run))
